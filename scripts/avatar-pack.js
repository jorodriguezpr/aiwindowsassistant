/**
 * Packs the SysAiBrain avatar into assets/sysaibrain/avatar.bin for the chat window.
 *
 * The SysAiBrain avatar (https://sysaibrain.com) is COMMERCIAL software by the same developer,
 * licensed to AiWindowsAssistant in binary form only. Its source is NOT part of this repository
 * and must never be: this script reads it (read-only) from a local SysAiBrain checkout
 * (SYSAIBRAIN_DIR, default C:\PhpProjects\SysAiBrain), minifies it, and writes a compressed
 * binary pack that ships only inside the Windows installer / .exe. assets/ is git-ignored and
 * gitdeploy never copies it. Without the pack (e.g. built from the GitHub source) the chat window
 * works without the avatar.
 *
 * The pack is ENCRYPTED (AES-256-GCM) with a fresh random key per build. The key is written only
 * into dist/avatar-key.js — build output, bundled inside the .exe, never in src/ or on GitHub —
 * so the only thing that ships is an opaque binary: no file that could be used to modify the
 * avatar. Usage terms: SYSAIBRAIN-AVATAR-LICENSE.txt (only as part of AiWindowsAssistant).
 *
 * Format: "SABAVTR2" (8) + IV (12) + GCM tag (16) + AES-256-GCM(gzip(JSON { v, js, mesh, notice })).
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SRC = process.env.SYSAIBRAIN_DIR || 'C:\\PhpProjects\\SysAiBrain';
const OUT = path.join(ROOT, 'assets', 'sysaibrain', 'avatar.bin');
const NOTICE =
  'SysAiBrain avatar (c) Jose Rodriguez Arroyo - https://sysaibrain.com - commercial software. Licensed for use ' +
  'only as part of AiWindowsAssistant, in binary form; no extraction, modification or use outside AiWindowsAssistant. ' +
  'See SYSAIBRAIN-AVATAR-LICENSE.txt. Not covered by the AiWindowsAssistant MIT license.';

async function main() {
  const jsFile = path.join(SRC, 'public', 'js', 'avatar.js');
  const meshFile = path.join(SRC, 'data', 'avatar', 'avatar-mesh.json');
  if (!fs.existsSync(jsFile) || !fs.existsSync(meshFile)) {
    console.log(`SysAiBrain avatar not found under ${SRC} — skipped (the chat window works without it).`);
    return;
  }
  const esbuild = require('esbuild');
  const min = await esbuild.transform(fs.readFileSync(jsFile, 'utf8'), {
    minify: true,
    legalComments: 'none',
    target: 'es2020',
    banner: `/*! ${NOTICE} */`,
  });
  const mesh = JSON.stringify(JSON.parse(fs.readFileSync(meshFile, 'utf8')));
  const plain = zlib.gzipSync(Buffer.from(JSON.stringify({ v: 2, js: min.code, mesh, notice: NOTICE }), 'utf8'), { level: 9 });
  const key = crypto.randomBytes(32);
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const body = Buffer.concat([cipher.update(plain), cipher.final()]);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, Buffer.concat([Buffer.from('SABAVTR2'), iv, cipher.getAuthTag(), body]));
  // the key: build output only (bundled into the .exe by pkg), never source, never published
  const keyFile = path.join(ROOT, 'dist', 'avatar-key.js');
  fs.mkdirSync(path.dirname(keyFile), { recursive: true });
  fs.writeFileSync(keyFile, `// generated by scripts/avatar-pack.js - build output, do not commit\nmodule.exports = Buffer.from('${key.toString('hex')}', 'hex');\n`);
  console.log(`SysAiBrain avatar packed (encrypted): ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
}

main().catch((err) => {
  console.error('avatar pack failed:', err.message);
  process.exit(1);
});
